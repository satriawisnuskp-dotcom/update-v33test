    fun findByCode(code: String): CurrencyOption {
        return allCurrencies.firstOrNull { it.code.equals(code, ignoreCase = true) }
            ?: allCurrencies.first()
    }

    fun formatAmount(amount: Double, currencyCode: String = "IDR"): String {
        val option = findByCode(currencyCode)
        val symbols = DecimalFormatSymbols(Locale.forLanguageTag("id-ID")).apply {
            groupingSeparator = '.'
            decimalSeparator = ','
        }
        val df = DecimalFormat("#,###", symbols)
        val formatted = df.format(amount.toLong())
        return "${option.symbol}$formatted"
    }
